public class CarSorter {
    private SortStrategy sortStrategy;

    public CarSorter(SortStrategy sortStrategy) {
        this.sortStrategy = sortStrategy;
    }

    public void setStrategy(SortStrategy sortStrategy) {
        this.sortStrategy = sortStrategy;
    }

    public SortStrategy getStrategy() {
        return sortStrategy;
    }

    public void sort(List<Car> cars) {
        // ????????? ?????????? ?? ????????? (?? ????????)
        Comparator<Car> defaultComparator = 
            Comparator.comparingDouble(Car::getPower);
        sortStrategy.sort(cars, defaultComparator);
    }
}
